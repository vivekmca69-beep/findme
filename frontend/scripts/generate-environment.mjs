import fs from 'node:fs';
import path from 'node:path';

const apiBaseUrl = (process.env.API_BASE_URL || 'http://localhost:5000').replace(/\/$/, '');
const googleMapsApiKey = process.env.GOOGLE_MAPS_API_KEY || '';

if (!/^https?:\/\//i.test(apiBaseUrl)) {
  console.error('API_BASE_URL must start with http:// or https://');
  process.exit(1);
}

if (!googleMapsApiKey) {
  console.warn('GOOGLE_MAPS_API_KEY is not set. The map will show a configuration message until a key is supplied.');
}

const output = `// AUTO-GENERATED by scripts/generate-environment.mjs\nexport const environment = {\n  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},\n  googleMapsApiKey: ${JSON.stringify(googleMapsApiKey)}\n};\n`;

const target = path.resolve('src/environments/environment.generated.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output, 'utf8');
console.log(`Generated ${target} with API base URL: ${apiBaseUrl} and Google Maps key: ${googleMapsApiKey ? 'configured' : 'missing'}`);
