import fs from 'node:fs';
import path from 'node:path';

const apiBaseUrl = (process.env.API_BASE_URL || 'http://localhost:5000').replace(/\/$/, '');

if (!/^https?:\/\//i.test(apiBaseUrl)) {
  console.error('API_BASE_URL must start with http:// or https://');
  process.exit(1);
}

const output = `// AUTO-GENERATED by scripts/generate-environment.mjs\nexport const environment = {\n  apiBaseUrl: ${JSON.stringify(apiBaseUrl)}\n};\n`;

const target = path.resolve('src/environments/environment.generated.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output, 'utf8');
console.log(`Generated ${target} with API base URL: ${apiBaseUrl}`);
